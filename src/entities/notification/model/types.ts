import type { ID, ISODateString } from '@/shared/types'

/**
 * Уведомление в колокольчике шапки. Уведомления номинальные — один вид:
 * «Вы предложили обмен Ивану». «Перейти» открывает карточку Ивана.
 */
export interface Notification {
  id: ID
  /** Чьё это уведомление — кто предложил обмен и видит его в колокольчике */
  userId: ID
  /** Кому предложили обмен — его имя в тексте и его карточка по «Перейти» */
  toUserId: ID
  exchangeId: ID
  /** Прочитанные уходят в «Просмотренные» и больше не кликаются */
  isRead: boolean
  createdAt: ISODateString
}
