import type { ID, ISODateString } from '@/shared/types'

/**
 * Предложение обмена. По решению наставника обмен «номинальный»: второй стороны нет,
 * предложение только создаётся — статусов «принят / отклонён» не делаем.
 */
export interface Exchange {
  id: ID
  /** Кто предложил — текущий пользователь */
  fromUserId: ID
  /** Кому предложили */
  toUserId: ID
  /** Навык получателя */
  skillId: ID
  /** Технический признак: предложение записано, но уведомление ещё нужно завершить.
   * Отсутствие поля у старых записей означает завершённую операцию. Это не статус обмена. */
  notificationPending?: boolean
  createdAt: ISODateString
}
